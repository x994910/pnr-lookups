const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');

const sections = ['syntax', 'segment-readers', 'booking', 'itinerary', 'form-fields', 'templates'];
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8').replace(/\r\n/g, '\n');
const html = read('MyPOI.html');
const filename = html.match(/const ENGINE_FILE = '(pnr-engine-[\d.]+\.js)'/)[1];
const source = sections.map(name => '\n  // ' + name + '\n' + read('engine/' + name + '.js')).join('');
const bundle = "// Generated by build.cjs. Edit the files in engine/.\n'use strict';\nglobalThis.MyPOIEngine = (() => {\n" +
  source + '  return {tokenize,dateParts,time,readTIF,readDOCS,readTVL,readRCI,readTBD,parse,route,localInstant,toNZ,baggage,csv,contacts,fillTemplate,derive,pretty};\n})();\n';
const integrity = 'sha384-' + createHash('sha384').update(bundle).digest('base64');
const updated = html.replace(/const ENGINE_INTEGRITY = '[^']*'/, "const ENGINE_INTEGRITY = '" + integrity + "'");
if (process.argv.includes('--check')) {
  if (html !== updated || read(filename) !== bundle) throw Error('Engine bundle or HTML integrity is out of date.');
} else {
  fs.writeFileSync(path.join(__dirname, filename), bundle);
  fs.writeFileSync(path.join(__dirname, 'MyPOI.html'), updated);
}
